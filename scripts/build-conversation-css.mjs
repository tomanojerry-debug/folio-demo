import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const scope = '.conversation-surface';

function selectors(value) {
  const result=[]; let start=0, depth=0, quote='';
  for (let i=0;i<value.length;i++) {
    const c=value[i];
    if (quote) { if(c==='\\')i++;else if(c===quote)quote='';continue; }
    if(c==='"'||c==="'")quote=c;
    else if(c==='('||c==='[')depth++;
    else if(c===')'||c===']')depth--;
    else if(c===','&&!depth){result.push(value.slice(start,i));start=i+1;}
  }
  result.push(value.slice(start)); return result;
}

function scopeSelector(selector) {
  let value=selector.trim();
  // Prefixing an ordinary rule adds one class. Replacing a body state must
  // retain its existing class and element weight as well as that scope class,
  // otherwise later workspace rules can lose to earlier .button.btn rules.
  value=value.replace(/:root\b/g,`${scope}${scope}`)
    .replace(/\bbody\.(?:is-workspace-chat|is-chat)\b/g,`${scope}${scope}:is(div)`)
    .replace(/\bbody\b/g,`${scope}:is(div)`);
  if(value.includes(scope))return value;
  const html=value.match(/^(html[^\s]*)(?:\s+(.*))?$/);
  return html ? `${html[1]} ${scope}${html[2]?` ${html[2]}`:''}` : `${scope} ${value}`;
}

/** Scope the controlled component CSS, including nested media/supports rules. */
export function scopeConversationCss(source) {
  const input=source.replace(/\/\*[\s\S]*?\*\//g,'');
  function rules(css) {
    let output='', cursor=0;
    while(cursor<css.length) {
      const start=css.indexOf('{',cursor);
      if(start<0){if(css.slice(cursor).trim())throw new Error('Unexpected CSS statement');break;}
      const prelude=css.slice(cursor,start).trim();
      let end=start+1,depth=1,quote='';
      for(;end<css.length&&depth;end++) {
        const c=css[end];
        if(quote){if(c==='\\')end++;else if(c===quote)quote='';continue;}
        if(c==='"'||c==="'")quote=c;else if(c==='{')depth++;else if(c==='}')depth--;
      }
      if(depth)throw new Error('Unclosed CSS rule');
      const body=css.slice(start+1,end-1);
      if(/^@(?:media|supports|container|layer)\b/.test(prelude))output+=`${prelude}{${rules(body)}}\n`;
      else if(/^@(?:-webkit-)?keyframes\b/.test(prelude))output+=`${prelude}{${body}}\n`;
      else if(prelude.startsWith('@'))throw new Error(`Unsupported component CSS rule: ${prelude}`);
      else output+=`${selectors(prelude).map(scopeSelector).join(',')}{${body}}\n`;
      cursor=end;
    }
    return output;
  }
  let result=rules(input);
  const names=[...result.matchAll(/@(?:-webkit-)?keyframes\s+([\w-]+)/g)].map(match=>match[1]);
  for(const name of new Set(names))result=result.replace(new RegExp(`\\b${name}\\b`,'g'),`conversation-${name}`);
  return result;
}

export async function buildConversationCss({check=false}={}) {
  const root=new URL('../',import.meta.url);
  const sources=['site/curator/styles.css','site/curator/workspace-chat.css','site/curator/task-progress.css'];
  const chunks=await Promise.all(sources.map(async file=>`/* Scoped from ${file} */\n${scopeConversationCss(await readFile(new URL(file,root),'utf8'))}`));
  const layout=await readFile(new URL('site/curator/embedded-conversation-layout.css',root),'utf8');
  const result=`/* Generated by node scripts/build-conversation-css.mjs.\n * Edit the canonical component sources or embedded-conversation-layout.css, then regenerate.\n * Every ordinary selector is rooted in .conversation-surface; keyframes use a private prefix. */\n${chunks.join('\n')}\n${layout}`;
  const target=new URL('site/curator/conversation-component.css',root);
  if(check){if(await readFile(target,'utf8')!==result)throw new Error('conversation-component.css needs regeneration');}
  else await writeFile(target,result);
}

if(process.argv[1]===fileURLToPath(import.meta.url))await buildConversationCss({check:process.argv.includes('--check')});
